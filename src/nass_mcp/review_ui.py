def render_review_html(rows: list[dict], audio_sha256: str) -> str:
    """Generate an offline review page with bounded, text-free clip metadata."""
    if (not isinstance(audio_sha256, str) or len(audio_sha256) != 64
            or any(ch not in "0123456789abcdef" for ch in audio_sha256)):
        raise ValueError("Expected lowercase SHA-256 audio digest")
    if not isinstance(rows, list) or not 1 <= len(rows) <= 200:
        raise ValueError("Expected 1..200 review clips")
    out = []
    for item in rows:
        # Whitelist the EXACT metadata keys required by the reviewer.
        name = item["clip_file"]
        if (not isinstance(name, str) or
                not name.startswith("clip_") or not name.endswith(".wav") or
                not name[5:-4].isdigit() or len(name[5:-4]) != 4):
            raise ValueError("Unexpected review clip filename")
        out.append({
            "id": str(item["id"]),
            "kind": item["kind"],
            "start_seconds": float(item["start_seconds"]),
            "end_seconds": float(item["end_seconds"]),
            "clip_file": name,
        })
    data = json.dumps({"audio_sha256": audio_sha256, "rows": out},
                      ensure_ascii=True, allow_nan=False, separators=(",", ":"))
    # A user-controlled row ID must never close the JSON script element.
    data = (data.replace("&", r"\u0026")
                .replace("<", r"\u003c")
                .replace(">", r"\u003e"))
    return _HTML.replace("__PAYLOAD__", data)
